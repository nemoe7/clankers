"""Check the installed DEBUG gate keeps a command line that reads the inbox quiet.

The gate lives in the profile generated by the preview installer, and the EXIT hook beside it
counts the agent's calls. This test rebuilds both from the installer source with a stub CLI, so
it runs without touching the real profile or state.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "skills" / "refs" / "arena-skill" / "scripts"))

import preview as preview_module

quiet_inbox_line = preview_module.quiet_inbox_line
INSTALLER = ROOT / "skills" / "refs" / "arena-skill" / "scripts" / "install.sh"

STUB = """#!/bin/sh
# The classifiers are pure, so the stub answers with the real ones.
if [ "$1" = "inbox-line" ]; then
  exec __PYTHON__ __PREVIEW__ inbox-line "$2"
fi
if [ "$1" = "ack-tick" ]; then
  exec __PYTHON__ __PREVIEW__ ack-tick "$2"
fi
if [ "$1" = "serve-tick" ]; then
  exec __PYTHON__ __PREVIEW__ serve-tick "$2"
fi
exit 1
"""


def gate_source() -> str:
  """Return the gate function as the installer writes it into the profile."""
  installer = INSTALLER.read_text(encoding="utf-8")
  match = re.search(
    r"# arena-preview-gate\n_arena_preview_gate\(\) \{.*?\n\}\nEOF",
    installer,
    re.DOTALL,
  )
  assert match, "installer must hold the gate function"
  block = match.group(0).removesuffix("\nEOF")
  # Unquoted heredocs drop one backslash before $, ` and backslash.
  block = block.replace("\\\\", "\x00").replace("\\$", "$").replace("\\`", "`")
  block = block.replace("\x00", "\\")
  return block.replace(
    '"$VENV/bin/python" "$REPO_ROOT/$SKILL_REL/scripts/preview.py"', '"$STUB"'
  )


def hook_source() -> str:
  """Return the EXIT hook as the installer writes it, with the CLI call left to $STUB."""
  installer = INSTALLER.read_text(encoding="utf-8")
  match = re.search(r'cat > "\$HOOK" <<EOF.*?\nEOF\n', installer, re.DOTALL)
  assert match, "installer must hold the hook script"
  body = match.group(0)
  body = body[body.index("<<EOF") + len("<<EOF") :].split("\n", 1)[1]
  assert body.endswith("\nEOF\n"), "the hook heredoc must close on its own line"
  body = body[: -len("\nEOF\n")]
  # Unquoted heredocs drop one backslash before $, ` and backslash.
  body = body.replace("\\\\", "\x00").replace("\\$", "$").replace("\\`", "`")
  body = body.replace("\x00", "\\")
  return body.replace(
    '"$VENV/bin/python" "$REPO_ROOT/$SKILL_REL/scripts/preview.py" --reminder',
    '"$STUB"',
  )


def test_the_hook_skips_the_platform_shells() -> None:
  """A hosted process or a platform probe is not an agent call (owner note ef180f0)."""
  with tempfile.TemporaryDirectory() as directory:
    root = Path(directory)
    marker = root / "called"
    stub = root / "stub.sh"
    stub.write_text('#!/bin/sh\ntouch "' + str(marker) + '"\n', encoding="utf-8")
    stub.chmod(0o755)
    hook = root / "hook.sh"
    hook.write_text(hook_source(), encoding="utf-8")
    hook.chmod(0o755)
    env = {**os.environ, "STUB": str(stub)}
    # The platform hosts its processes in a login shell over run.cmd under arena-workspace.
    # `; exit 0` keeps the shaped shell alive as the hook's parent instead of exec'ing the hook.
    hosted = subprocess.run(
      [
        "bash",
        "-c",
        'exec -a "bash -l /tmp/arena-workspace/procs/x/run.cmd" bash -c "'
        + f'bash {hook}; exit 0"',
      ],
      capture_output=True,
      text=True,
      env=env,
      check=False,
    )
    assert hosted.returncode == 0
    assert not marker.exists(), "a hosted shell must not run the reminder"
    plain = subprocess.run(
      ["bash", "-c", f"bash {hook}; exit 0"],
      capture_output=True,
      text=True,
      env=env,
      check=False,
    )
    assert plain.returncode == 0
    assert marker.exists(), "an agent call still runs the reminder"


def run(command: str, cwd: str | None = None) -> subprocess.CompletedProcess[str]:
  """Run one command in a shell whose $0 is bash, the shape the gate protects."""
  with tempfile.TemporaryDirectory() as directory:
    root = Path(directory)
    stub = root / "stub.sh"
    import sys

    preview_module = ROOT / "skills" / "refs" / "arena-skill" / "scripts" / "preview.py"
    stub.write_text(
      STUB.replace("__PYTHON__", sys.executable).replace(
        "__PREVIEW__", str(preview_module)
      ),
      encoding="utf-8",
    )
    stub.chmod(0o755)
    # The tested command line may call the real CLI for its answer. A stub on PATH
    # keeps that answer free of an installation, so the test runs anywhere.
    bin_dir = root / "bin"
    bin_dir.mkdir()
    cli = bin_dir / "arena-preview"
    cli.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    cli.chmod(0o755)
    # The gate body stays in a sourced file: its own pattern text must not reach the
    # shell command line, because the guard reads that line.
    gate_file = root / "gate.sh"
    gate_file.write_text(gate_source() + "\n", encoding="utf-8")
    script = (
      "set -o functrace\n"
      "STUB=" + str(stub) + "\n"
      "REPO_ROOT=" + str(ROOT) + "\n"
      "SKILL_REL=.agents/skills/arena-skill\n"
      '. "'
      + str(gate_file)
      + '"\n'
      + "trap '_arena_preview_gate : # arena-preview-gate' DEBUG\n"
      + command
      + "\n"
    )
    return subprocess.run(
      ["bash", "--noprofile", "--norc", "-c", script],
      capture_output=True,
      text=True,
      check=False,
      cwd=cwd,
      env={**os.environ, "PATH": str(bin_dir) + os.pathsep + os.environ["PATH"]},
    )


def test_plain_chain_meets_the_count_gate():
  result = run("cd /tmp && echo ran")
  assert result.returncode == 130, result.stderr
  assert "ran" not in result.stdout


def test_a_read_alone_stays_quiet():
  # The read must reach its read, whatever the tally.
  result = run(': "arena-preview read"')
