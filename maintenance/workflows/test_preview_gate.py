from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "skills" / "refs" / "arena-skill" / "scripts"))

import preview as preview_module

quiet_inbox_line = preview_module.quiet_inbox_line
INSTALLER = ROOT / "skills" / "refs" / "arena-skill" / "scripts" / "install.sh"

STUB = """#!/bin/sh
# The merged gate runs the real rules, so the stub records and forwards it.
if [ -n "${ARENA_PREVIEW_TEST_CALLS:-}" ]; then
  printf '%s\\n' "$*" >> "$ARENA_PREVIEW_TEST_CALLS"
fi
if [ "$1" = "pre" ]; then
  exec __PYTHON__ __PREVIEW__ "$@"
fi
# A drift fixture has no inbox, so its dry-run push may reach Git.
if [ "$1" = "gate" ] && [ "${ARENA_PREVIEW_TEST_DRIFT:-}" = "1" ]; then
  exit 0
fi
exit 1
"""


def clean_env(**overrides: str) -> dict[str, str]:
  """The environment the gate meets, minus the marker a routed child exports.

  A shell that carries `ARENA_PREVIEW_ROUTE=1` skips the gate by design, so a suite
  started from a routed child must drop the marker or it tests nothing.
  """
  env = {
    key: value for key, value in os.environ.items() if key != "ARENA_PREVIEW_ROUTE"
  }
  env.update(overrides)
  return env


def gate_source() -> str:
  """Return the gate function as the installer writes it into the profile."""
  installer = INSTALLER.read_text(encoding="utf-8")
  match = re.search(
    r"# arena-preview-gate\n_arena_preview_gate\(\) \{.*?\n\}\nEOF",
    installer,
    re.DOTALL,
  )
  assert match, "installer must hold the gate function"
  block = match.group(0).removesuffix("\nEOF")
  # Unquoted heredocs drop one backslash before $, ` and backslash.
  block = block.replace("\\\\", "\x00").replace("\\$", "$").replace("\\`", "`")
  block = block.replace("\x00", "\\")
  return block.replace(
    '"$VENV/bin/python" "$REPO_ROOT/$SKILL_REL/scripts/preview.py"', '"$STUB"'
  )


def hook_source() -> str:
  """Return the EXIT hook as the installer writes it, with the CLI call left to $STUB."""
  installer = INSTALLER.read_text(encoding="utf-8")
  match = re.search(r'cat > "\$HOOK" <<EOF.*?\nEOF\n', installer, re.DOTALL)
  assert match, "installer must hold the hook script"
  body = match.group(0)
  body = body[body.index("<<EOF") + len("<<EOF") :].split("\n", 1)[1]
  assert body.endswith("\nEOF\n"), "the hook heredoc must close on its own line"
  body = body[: -len("\nEOF\n")]
  # Unquoted heredocs drop one backslash before $, ` and backslash.
  body = body.replace("\\\\", "\x00").replace("\\$", "$").replace("\\`", "`")
  body = body.replace("\x00", "\\")
  return body.replace(
    '"$VENV/bin/python" "$REPO_ROOT/$SKILL_REL/scripts/preview.py" --reminder',
    '"$STUB"',
  )


def test_the_hook_skips_the_platform_shells() -> None:
  """A hosted process or a platform probe is not an agent call."""
  with tempfile.TemporaryDirectory() as directory:
    root = Path(directory)
    marker = root / "called"
    stub = root / "stub.sh"
    stub.write_text('#!/bin/sh\ntouch "' + str(marker) + '"\n', encoding="utf-8")
    stub.chmod(0o755)
    hook = root / "hook.sh"
    hook.write_text(hook_source(), encoding="utf-8")
    hook.chmod(0o755)
    env = clean_env(STUB=str(stub))
    # The platform hosts its processes in a login shell over run.cmd under arena-workspace.
    # `. Exit 0` keeps the shaped shell alive as the hook's parent instead of exec'ing the hook.
    for argv0 in (
      "bash -l /tmp/arena-workspace/procs/x/run.cmd",
      "/bin/bash -l -c mkdir -p 'arena-state'",
      "/bin/bash -l -c [ -e 'ARENA.md' ] && [ ! -d 'ARENA.md' ]",
      "/bin/bash -l -c python3 -I - <<'PY'",
    ):
      hosted = subprocess.run(
        [
          "bash",
          "-c",
          f'exec -a {shlex.quote(argv0)} bash -c "bash {hook}; exit 0"',
        ],
        capture_output=True,
        text=True,
        env=env,
        check=False,
      )
      assert hosted.returncode == 0
      assert not marker.exists(), f"{argv0} must not run the reminder"
    plain = subprocess.run(
      ["bash", "-c", f"bash {hook}; exit 0"],
      capture_output=True,
      text=True,
      env=env,
      check=False,
    )
    assert plain.returncode == 0
    assert marker.exists(), "an agent call still runs the reminder"


def run(
  command: str,
  cwd: str | None = None,
  state: Path | None = None,
  line: str | None = None,
  calls: Path | None = None,
  routed: bool = False,
) -> subprocess.CompletedProcess[str]:
  """Run one command in a shell whose $0 is bash, the shape the gate protects."""
  if state is None:
    with tempfile.TemporaryDirectory() as directory:
      return run_in(command, Path(directory), cwd, line, calls, routed)
  return run_in(command, state, cwd, line, calls, routed)


def run_in(
  command: str,
  root: Path,
  cwd: str | None = None,
  line: str | None = None,
  calls: Path | None = None,
  routed: bool = False,
) -> subprocess.CompletedProcess[str]:
  """Run one command against a state directory, with the gate sourced and trapped.

  A caller may pass the command line the gate reads, which carries the shell invocation
  that the platform puts in front of every script. A caller may also ask the stub to
  log the calls it answered, which shows whether a line reached the gate at all.
  """
  stub = root / "stub.sh"
  import sys

  preview_module = ROOT / "skills" / "refs" / "arena-skill" / "scripts" / "preview.py"
  stub.write_text(
    STUB.replace("__PYTHON__", sys.executable).replace(
      "__PREVIEW__", str(preview_module)
    ),
    encoding="utf-8",
  )
  stub.chmod(0o755)
  # The tested command line may call the real CLI for its answer. A stub on PATH
  # keeps that answer free of an installation, so the test runs anywhere.
  bin_dir = root / "bin"
  bin_dir.mkdir(exist_ok=True)
  cli = bin_dir / "arena-preview"
  cli.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
  cli.chmod(0o755)
  # The gate body stays in a sourced file: its own pattern text must not reach the
  # shell command line, because the guard reads that line.
  gate_file = root / "gate.sh"
  gate_file.write_text(gate_source() + "\n", encoding="utf-8")
  script = (
    "set -o functrace\n"
    "STUB=" + str(stub) + "\n"
    "REPO_ROOT=" + str(ROOT) + "\n"
    "SKILL_REL=.agents/skills/arena-skill\n"
    '. "'
    + str(gate_file)
    + '"\n'
    + "_arena_preview_line="
    + shlex.quote(line if line is not None else command)
    + "\n"
    + "trap '_arena_preview_gate : # arena-preview-gate' DEBUG\n"
    + command
    + "\n"
  )
  return subprocess.run(
    ["bash", "--noprofile", "--norc", "-c", script],
    capture_output=True,
    text=True,
    check=False,
    cwd=cwd,
    env=clean_env(
      PATH=str(bin_dir) + os.pathsep + os.environ["PATH"],
      # The tick writes its record under the temp state and starts no real wait.
      ARENA_PREVIEW_STATE_DIR=str(root),
      ARENA_PREVIEW_DETACH_DRY="1",
      **({"ARENA_PREVIEW_ROUTE": "1"} if routed else {}),
      ARENA_PREVIEW_TEST_DRIFT="1" if cwd else "0",
      **({"ARENA_PREVIEW_TEST_CALLS": str(calls)} if calls else {}),
    ),
  )


REFERENCE = ROOT / "maintenance" / "README.md"


def test_the_reference_table_holds_every_gate_case() -> None:
  """Every labelled case of the hook and the merged gate appears in the reference."""
  source = INSTALLER.read_text(encoding="utf-8")
  source += Path(preview_module.__file__).read_text(encoding="utf-8")
  labels = set(re.findall(r"^\s*# case: ([a-z][a-z0-9-]*)$", source, re.MULTILINE))
  assert len(labels) >= 10, sorted(labels)
  reference = REFERENCE.read_text(encoding="utf-8")
  section = reference.split("## The gate's cases", 1)
  assert len(section) == 2, "maintenance/README.md must carry the case table"
  section = section[1].split("\n## ", 1)[0]
  rows = set(re.findall(r"^\| `([a-z][a-z0-9-]*)` \|", section, re.MULTILINE))
  assert rows == labels, (
    f"table rows without a case: {sorted(rows - labels)}; "
    f"cases without a row: {sorted(labels - rows)}"
  )


